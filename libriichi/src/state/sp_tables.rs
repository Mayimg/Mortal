// ========================================================================
// SinglePlayerTables: シングルプレイヤー麻雀の戦略計算結果を保持する構造体
// ========================================================================
//
// このモジュールは、シングルプレイヤー麻雀における最適な打牌戦略の計算結果を
// 格納するためのデータ構造を定義します。
//
// 主な役割：
// - SPCalculator（シングルプレイヤー計算機）によって計算された各打牌候補の
//   期待値、和了確率、聴牌確率などの詳細な評価結果を保持
// - AIエージェントが最適な打牌を決定する際の基礎データとして使用
// - ニューラルネットワークモデルへの入力特徴量として利用
//
// 処理の流れ：
// 1. PlayerState::single_player_tables() が呼び出される
// 2. SPCalculator が現在の手牌状態から全ての打牌候補を評価
// 3. 各候補について期待値、和了確率、聴牌確率を動的計画法で計算
// 4. 結果を期待値の降順でソートしてmax_ev_tableに格納
// 5. AIエージェントは最も期待値の高い候補（インデックス0）を選択

// algo::sp::Candidate構造体をインポート
// Candidateは一つの打牌候補とその評価結果（期待値、和了確率、聴牌確率、
// 必要牌情報など）を包含する構造体
use crate::algo::sp::Candidate;

// シングルプレイヤー麻雀の戦略計算結果を保持する構造体
pub struct SinglePlayerTables {
    // 期待値順（降順）にソートされた打牌候補のベクタ
    // max_ev_table[0]が最も期待値の高い（最適な）打牌候補
    // 各Candidateには以下の情報が含まれる：
    // - tile: 打牌する牌
    // - tenpai_probs: 各巡目での聴牌確率（最大17巡先まで）
    // - win_probs: 各巡目での和了確率（最大17巡先まで）  
    // - exp_values: 各巡目での期待得点（最大17巡先まで）
    // - required_tiles: この牌を切った後の有効牌リスト
    // - num_required_tiles: 有効牌の総枚数
    // - shanten_down: この打牌でシャンテン数が増加するかどうか
    pub max_ev_table: Vec<Candidate>,
}
