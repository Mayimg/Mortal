// このファイルは麻雀のチー（チョウ/吃）における、鳴いた牌の位置を表すChiType列挙型を定義しています。
// チーは3枚の連続した数牌で構成される順子（シュンツ）を作る鳴きです。
// プレイヤーは手牌から2枚を使い、他家が捨てた1枚と組み合わせて順子を作ります。
// ChiTypeは、鳴いた牌が順子の中でどの位置（低位・中位・高位）にあるかを表します。

use crate::tile::Tile;  // 麻雀の牌を表すTile型をインポート

// チーにおける鳴いた牌の位置を表す列挙型
// 例: 手牌に2萬と3萬があり、1萬を鳴いた場合はLow（低位）
//     手牌に1萬と3萬があり、2萬を鳴いた場合はMid（中位）
//     手牌に1萬と2萬があり、3萬を鳴いた場合はHigh（高位）
#[derive(Clone, Copy)]  // このenumはコピー可能で、値をクローンできる
pub enum ChiType {
    Low,   // 鳴いた牌が順子の最小値（例: 1-2-3の1）
    Mid,   // 鳴いた牌が順子の中間値（例: 1-2-3の2）
    High,  // 鳴いた牌が順子の最大値（例: 1-2-3の3）
}

impl ChiType {
    // 手牌から使った2枚の牌と鳴いた牌から、ChiTypeを判定するコンストラクタ
    // consumed: 手牌から使った2枚の牌の配列
    // tile: 他家が捨てて鳴いた牌
    #[must_use]  // この関数の戻り値を使わない場合はコンパイラが警告を出す
    pub fn new(consumed: [Tile; 2], tile: Tile) -> Self {
        // 手牌の1枚目を赤ドラでない通常の牌に変換してからu8型の数値として取得
        // deaka()は赤5を通常の5に変換する（例: 5萬赤 → 5萬）
        let a = consumed[0].deaka().as_u8();
        
        // 手牌の2枚目も同様に処理
        let b = consumed[1].deaka().as_u8();
        
        // 手牌の2枚のうち小さい方の値を取得
        let min = a.min(b);
        
        // 手牌の2枚のうち大きい方の値を取得
        let max = a.max(b);
        
        // 鳴いた牌も赤ドラでない通常の牌に変換してからu8型の数値として取得
        let tile_id = tile.deaka().as_u8();
        
        // 鳴いた牌が手牌の最小値より小さい場合
        // 例: 手牌が2-3で、鳴いた牌が1の場合
        if tile_id < min {
            Self::Low  // 低位チー
        // 鳴いた牌が手牌の最小値と最大値の間にある場合
        // 例: 手牌が1-3で、鳴いた牌が2の場合
        } else if tile_id < max {
            Self::Mid  // 中位チー
        // それ以外（鳴いた牌が手牌の最大値以上）の場合
        // 例: 手牌が1-2で、鳴いた牌が3の場合
        } else {
            Self::High  // 高位チー
        }
    }
}
