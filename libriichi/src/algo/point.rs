//! 麻雀の点数計算を行うモジュール
//!
//! このモジュールは符と飜数から実際の支払い点数を計算します。
//! ロン和了時の支払い点数、ツモ和了時の子・親それぞれの支払い点数を含みます。
//! 役満の場合は符計算を行わず、倍数から直接点数を算出します。

// 点数情報を表す構造体
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq)]
pub struct Point {
    pub ron: i32,         // ロン和了時の支払い点数
    pub tsumo_ko: i32,    // ツモ和了時の子の支払い点数
    pub tsumo_oya: i32,   // ツモ和了時の親の支払い点数（親番の場合は常に0）
}

impl Point {
    /// 符と飜数から点数を計算
    ///
    /// # パニック
    /// 不可能な符と飜の組み合わせが指定された場合にパニックする
    ///
    /// # 引数
    /// - `is_oya`: 和了者が親かどうか
    /// - `fu`: 符数
    /// - `han`: 飜数
    ///
    /// # 戻り値
    /// 計算された点数情報。`is_oya`が真の場合、`tsumo_oya`は常に0になる。
    #[must_use]
    pub fn calc(is_oya: bool, fu: u8, han: u8) -> Self {
        // 点数テーブルから対応する点数を取得
        // 親と子で異なる点数体系を使用
        let (ron, tsumo_ko, tsumo_oya) = if is_oya {
            // 親の場合の点数表（ロン、子のツモ支払い、親のツモ支払い=0）
            match (fu, han) {
                // 20符の系列
                (20, 2) | (40, 1) => (2000, 700, 0),
                (20, 3) | (40, 2) | (80, 1) => (3900, 1300, 0),
                (20, 4) | (40, 3) | (80, 2) => (7700, 2600, 0),
                // 25符（七対子）の系列
                (25, 2) | (50, 1) => (2400, 800, 0),
                (25, 3) | (50, 2) | (100, 1) => (4800, 1600, 0),
                (25, 4) | (50, 3) | (100, 2) => (9600, 3200, 0),
                // 30符の系列（最も一般的）
                (30, 1) => (1500, 500, 0),
                (30, 2) | (60, 1) => (2900, 1000, 0),
                (30, 3) | (60, 2) => (5800, 2000, 0),
                (30, 4) | (60, 3) => (11600, 3900, 0),
                // 70符の系列
                (70, 1) => (3400, 1200, 0),
                (70, 2) => (6800, 2300, 0),
                // 90符の系列
                (90, 1) => (4400, 1500, 0),
                (90, 2) => (8700, 2900, 0),
                // 110符の系列（理論値、実際には110符1飜のツモは不可能）
                (110, 1) => (5300, 1800, 0),
                (110, 2) => (10600, 3600, 0),
                // 満貫以上（符計算不要）
                (_, 5) | (40.., 4) | (70.., 3) => (12000, 4000, 0),    // 満貫
                (_, 6..=7) => (18000, 6000, 0),                         // 跳満
                (_, 8..=10) => (24000, 8000, 0),                        // 倍満
                (_, 11..=12) => (36000, 12000, 0),                      // 三倍満
                (_, 13..) => (48000, 16000, 0),                         // 数え役満
                _ => panic!("impossible combinition of {fu} fu and {han} han"),
            }
        } else {
            // 子の場合の点数表（ロン、子のツモ支払い、親のツモ支払い）
            match (fu, han) {
                // 20符の系列
                (20, 2) | (40, 1) => (1300, 400, 700),
                (20, 3) | (40, 2) | (80, 1) => (2600, 700, 1300),
                (20, 4) | (40, 3) | (80, 2) => (5200, 1300, 2600),
                // 25符（七対子）の系列
                (25, 2) | (50, 1) => (1600, 400, 800),
                (25, 3) | (50, 2) | (100, 1) => (3200, 800, 1600),
                (25, 4) | (50, 3) | (100, 2) => (6400, 1600, 3200),
                // 30符の系列（最も一般的）
                (30, 1) => (1000, 300, 500),
                (30, 2) | (60, 1) => (2000, 500, 1000),
                (30, 3) | (60, 2) => (3900, 1000, 2000),
                (30, 4) | (60, 3) => (7700, 2000, 3900),
                // 70符の系列
                (70, 1) => (2300, 600, 1200),
                (70, 2) => (4500, 1200, 2300),
                // 90符の系列
                (90, 1) => (2900, 800, 1500),
                (90, 2) => (5800, 1500, 2900),
                // 110符の系列（理論値、実際には110符1飜のツモは不可能）
                (110, 1) => (3600, 900, 1800),
                (110, 2) => (7100, 1800, 3600),
                // 満貫以上（符計算不要）
                (_, 5) | (40.., 4) | (70.., 3) => (8000, 2000, 4000),   // 満貫
                (_, 6..=7) => (12000, 3000, 6000),                      // 跳満
                (_, 8..=10) => (16000, 4000, 8000),                     // 倍満
                (_, 11..=12) => (24000, 6000, 12000),                   // 三倍満
                (_, 13..) => (32000, 8000, 16000),                      // 数え役満
                _ => panic!("impossible combinition of {fu} fu and {han} han"),
            }
        };
        // 点数構造体を生成して返す
        Self {
            ron,
            tsumo_ko,
            tsumo_oya,
        }
    }

    /// 役満の点数を計算
    ///
    /// # 引数
    /// - `is_oya`: 和了者が親かどうか
    /// - `count`: 役満の倍数（1=役満、2=ダブル役満など）
    ///
    /// # 戻り値
    /// 役満の点数情報
    #[inline]
    #[must_use]
    pub const fn yakuman(is_oya: bool, count: i32) -> Self {
        if is_oya {
            // 親の役満：48000点（子16000点オール）
            Self {
                ron: 48000 * count,
                tsumo_ko: 16000 * count,
                tsumo_oya: 0,
            }
        } else {
            // 子の役満：32000点（子8000点、親16000点）
            Self {
                ron: 32000 * count,
                tsumo_ko: 8000 * count,
                tsumo_oya: 16000 * count,
            }
        }
    }

    /// ツモ和了時の合計収入を計算
    ///
    /// # 引数
    /// - `is_oya`: 和了者が親かどうか
    ///
    /// # 戻り値
    /// ツモ和了時の合計収入点数
    #[inline]
    #[must_use]
    pub const fn tsumo_total(self, is_oya: bool) -> i32 {
        if is_oya {
            // 親のツモ：子3人から同額を受け取る
            self.tsumo_ko * 3
        } else {
            // 子のツモ：子2人と親1人から受け取る
            self.tsumo_ko * 2 + self.tsumo_oya
        }
    }
}

#[cfg(test)]
mod test {
    use super::*;
    use std::iter::once;

    /// 点数表の正確性を検証するテスト
    #[test]
    fn table() {
        // 全ての符（20-110、10刻み、および25符）について
        for fu in (20..=110).step_by(10).chain(once(25)) {
            // 1飜から14飜まで
            for han in 1..=14 {
                // 1飜は30符以上でないと成立しない
                if han == 1 && fu < 30 {
                    continue;
                }

                // 基本点を計算（満貫以上は固定値）
                let base_points = if han >= 13 {
                    8000  // 数え役満
                } else if han >= 11 {
                    6000  // 三倍満
                } else if han >= 8 {
                    4000  // 倍満
                } else if han >= 6 {
                    3000  // 跳満
                } else if han >= 5 {
                    2000  // 満貫
                } else {
                    // 満貫未満：符 × 2^(飜数+2)、ただし2000点を上限とする
                    (fu * 2_i32.pow(2 + han)).min(2000)
                };
                // 基本点に倍率をかけて100点単位に切り上げ
                let get_points = |mult| (base_points * mult + 99) / 100 * 100;

                // 子の点数計算を検証
                let points_ko = Point::calc(false, fu as u8, han as u8);
                assert_eq!(points_ko.tsumo_ko, get_points(1), "{fu}/{han}");   // 子の支払い：基本点×1
                assert_eq!(points_ko.tsumo_oya, get_points(2), "{fu}/{han}");  // 親の支払い：基本点×2
                assert_eq!(points_ko.ron, get_points(4), "{fu}/{han}");        // ロン：基本点×4

                // 親の点数計算を検証
                let points_oya = Point::calc(true, fu as u8, han as u8);
                assert_eq!(points_oya.tsumo_ko, get_points(2), "{fu}/{han}");  // 子の支払い：基本点×2
                assert_eq!(points_oya.ron, get_points(6), "{fu}/{han}");       // ロン：基本点×6
            }
        }
    }
}
